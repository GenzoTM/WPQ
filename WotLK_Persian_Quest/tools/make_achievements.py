#!/usr/bin/env python3
"""Build Database_Achievements.lua from translations_achievements.json.

Usage:  python make_achievements.py translations_achievements.json ../Database_Achievements.lua

JSON: {"achievements": [ {"id": 2155, "name_en": "Abuse the Ooze", "description": "Persian text"} ]}
Only the DESCRIPTION is translated; achievement names stay English. Entries are keyed by
achievement ID (see the wowhead URL: /achievement=2155), so the English text does not need to match.
"~" is converted to a half-space (ZWNJ).
"""
import json, sys

def norm(s):
    s = s.replace("~", "\u200c").replace("\u064a", "\u06cc").replace("\u0643", "\u06a9").replace("|", "")
    return s.strip()

def main(src, dst):
    data = json.load(open(src, encoding="utf-8"))
    out = ["-- Generated by tools/make_achievements.py - edit translations_achievements.json, not this file.",
           "WPQ_DB = WPQ_DB or {}", "WPQ_DB.achievements = WPQ_DB.achievements or {}"]
    for a in data["achievements"]:
        d = norm(a["description"])
        if "]==]" in d: raise ValueError("text contains ]==]")
        out.append("WPQ_DB.achievements[%d] = [==[%s]==]  -- %s" % (int(a["id"]), d, a.get("name_en", "")))
    out.append("")
    open(dst, "w", encoding="utf-8").write("\n".join(out))
    print("wrote %s: %d achievements" % (dst, len(data["achievements"])))

if __name__ == "__main__":
    if len(sys.argv) != 3: print(__doc__); sys.exit(1)
    main(sys.argv[1], sys.argv[2])
