#!/usr/bin/env python3
"""Build Database.lua from translations.json.

Usage:  python make_db.py translations.json ../Database.lua

translations.json = {"quests": [ {...}, {...} ]}. Fields per quest:
  title_en     English title exactly as shown in game (required unless "id" is used alone)
  id           optional quest ID (use it when two quests share a title)
  title        Persian title
  description  Persian text of the Description block (use a blank line between paragraphs)
  objectives   Persian text of the Objectives block
  progress     Persian text of the progress window ("Continue / Cancel")
  completion   Persian text of the completion window ("Complete Quest")
  faction      optional "A" (Alliance) or "H" (Horde); used when two quests share one title
  lines        {"English objective line": "Persian line"}  (no "0/5" counters)
In texts: real half-space (U+200C) is kept; "~" is converted to a half-space for easy typing.
Variables $n $c $r $g<male>:<female>; and $b (line break) are supported.
"""
import json, re, sys

FIELDS = ["title", "description", "objectives", "progress", "completion"]
ZWNJ = "\u200c"

def norm(s):
    s = s.replace("\r\n", "\n").replace("\r", "\n").replace("~", ZWNJ)
    s = s.replace("\u064a", "\u06cc").replace("\u0643", "\u06a9")   # Arabic yeh/kaf -> Persian
    s = s.replace("|", "")
    return s.strip()

def key(s):
    """Quoted Lua string for table keys ([[ ]] would be parsed as a long string)."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'

def lua(s):
    if "]==]" in s:
        raise ValueError("text contains ]==]")
    return "[==[" + ("\n" if s.startswith("\n") else "") + s + "]==]"

def main(src, dst):
    data = json.load(open(src, encoding="utf-8"))
    by_title, by_id = [], []
    for q in data["quests"]:
        name = q.get("title_en") or ("id %s" % q.get("id"))
        body = []
        if q.get("id") and q.get("title_en"):
            body.append("    titleEn = %s," % lua(q["title_en"]))
        if q.get("faction") in ("A", "H"):
            body.append('    f = "%s",' % q["faction"])
        for f in FIELDS:
            if q.get(f):
                v = norm(q[f])
                if re.search(r"[A-Za-z]{4,}", re.sub(r"\$[a-zA-Z]", "", v)) and f != "title":
                    print("warning: %s.%s still has Latin words" % (name, f))
                body.append("    %s = %s," % (f, lua(v)))
        if q.get("lines"):
            body.append("    lines = {")
            for k, v in q["lines"].items():
                body.append("      [%s] = %s," % (key(k), lua(norm(v))))
            body.append("    },")
        block = "{\n" + "\n".join(body) + "\n  }"
        if q.get("id"):
            by_id.append("WPQ_DB.quests[%d] = %s" % (int(q["id"]), block))
        else:
            by_title.append("WPQ_DB.questTitles[%s] = %s" % (key(q["title_en"]), block))
    # merge-style output: several Database*.lua files can be loaded one after another
    out = ["-- Generated by tools/make_db.py - edit the translations JSON, not this file.",
           "WPQ_DB = WPQ_DB or {}", "WPQ_DB.quests = WPQ_DB.quests or {}",
           "WPQ_DB.questTitles = WPQ_DB.questTitles or {}"] + by_id + by_title + [""]
    open(dst, "w", encoding="utf-8").write("\n".join(out))
    print("wrote %s: %d by title, %d by id" % (dst, len(by_title), len(by_id)))

if __name__ == "__main__":
    if len(sys.argv) != 3:
        print(__doc__); sys.exit(1)
    main(sys.argv[1], sys.argv[2])
