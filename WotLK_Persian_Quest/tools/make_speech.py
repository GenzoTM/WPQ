#!/usr/bin/env python3
"""Build a Lua speech/gossip database from a JSON file.

Usage: python3 make_speech.py speech_icc.json ../Database_Speech_ICC.lua

JSON: {"speech": {"English line": "Persian"}, "names": ["Professor Putricide"],
       "gossip": {"English greeting": "Persian"}, "options": {"English option": "Persian"}}
  - "%s" in a line stands for the speaker's name, "$n" for the player's name.
  - "~" in the Persian text becomes a half-space (ZWNJ).
Keys are normalised exactly like Speech.lua does (no |T..|t icons, no colour codes, single spaces).
"""
import json, re, sys

def norm(s):
    s = re.sub(r"\|T.*?\|t", "", s)
    s = re.sub(r"\|c[0-9a-fA-F]{8}", "", s)
    s = s.replace("|r", "")
    return re.sub(r"\s+", " ", s).strip()

def lua(s):
    s = s.replace("~", "\u200c")
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'

def main(src, dst):
    d = json.load(open(src, encoding="utf-8"))
    out = ["-- Generated by tools/make_speech.py - edit the JSON, not this file.",
           "WPQ_DB = WPQ_DB or {}"]
    for tbl in ("speech", "gossip", "options"):
        if d.get(tbl):
            out.append("WPQ_DB.%s = WPQ_DB.%s or {}" % (tbl, tbl))
            for k, v in d[tbl].items():
                out.append("WPQ_DB.%s[%s] = %s" % (tbl, lua(norm(k).replace("~", "")), lua(v)))
    if d.get("names"):
        out.append("WPQ_DB.speechNames = WPQ_DB.speechNames or {}")
        for n in d["names"]:
            out.append("WPQ_DB.speechNames[%s] = true" % lua(n))
    open(dst, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("wrote", dst, {t: len(d.get(t, {})) for t in ("speech", "gossip", "options")})

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
